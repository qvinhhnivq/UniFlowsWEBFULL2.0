export function getCurrentLang() {
  return localStorage.getItem('uniflows-lang') || 'vi';
}

export function setLang(lang) {
  localStorage.setItem('uniflows-lang', lang);
  applyTranslations(lang);
}

export function t(key, params = {}, lang = getCurrentLang()) {
  let str = translations[lang]?.[key] || translations['vi']?.[key] || key;
  if (typeof params === 'object' && params !== null) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return str;
}

export function applyTranslations(lang = getCurrentLang()) {
  document.documentElement.lang = lang;
  
  // Translate elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang]?.[key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Translate input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang]?.[key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update language toggle buttons in card-nav
  if (window.cardNavInstance && typeof window.cardNavInstance.setLanguage === 'function') {
    window.cardNavInstance.setLanguage(lang);
  }

  // Update traditional language toggle text
  document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
    btn.innerHTML = lang === 'vi' ? '🇬🇧 English' : '🇻🇳 Tiếng Việt';
  });

  // Broadcast language change to portal and other components
  window.dispatchEvent(new CustomEvent('uniflows-lang-change', { detail: { lang } }));
}


